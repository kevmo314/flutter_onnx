f = lambda a: np.asarray(a, dtype=np.float32)
i64 = lambda a: np.asarray(a, dtype=np.int64)


def model(name, nodes, inputs, weights, outputs, version=13):
    def info(key, value):
        return h.make_tensor_value_info(
            key, T.FLOAT if value.dtype == np.float32 else T.INT64, value.shape
        )

    graph = h.make_graph(
        nodes,
        name,
        [info(k, v) for k, v in inputs.items()],
        [h.make_tensor_value_info(k, t, shape) for k, t, shape in outputs],
        [numpy_helper.from_array(v, k) for k, v in weights.items()],
    )
    m = h.make_model(graph, ir_version=8, opset_imports=[h.make_opsetid("", version)])
    onnx.checker.check_model(m)
    actual = ReferenceEvaluator(m).run(None, inputs)

    def tensor(v):
        return [str(v.dtype), list(v.shape), v.flatten().tolist()]

    cases.append(
        dict(
            name=name,
            model=base64.b64encode(m.SerializeToString()).decode(),
            feeds={k: tensor(v) for k, v in inputs.items()},
            outputs={o[0]: tensor(v) for o, v in zip(outputs, actual)},
        )
    )
    return m


def single(
    op, args, shape, attrs=None, weights=None, dtype=T.FLOAT, label=None, version=13
):
    weights = weights or {}
    return model(
        label or op,
        [h.make_node(op, list(args) + list(weights), ["y"], **(attrs or {}))],
        args,
        weights,
        [("y", dtype, shape)],
        version,
    )


